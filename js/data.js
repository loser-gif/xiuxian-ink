const CN_DIGITS = '零一二三四五六七八九';
function cn(n) {
  n = Math.floor(Math.max(0, n));
  if (n < 10) return CN_DIGITS[n];
  if (n < 20) return '十' + (n % 10 ? CN_DIGITS[n % 10] : '');
  if (n < 100) return CN_DIGITS[Math.floor(n / 10)] + '十' + (n % 10 ? CN_DIGITS[n % 10] : '');
  if (n < 1000) {
    const h = Math.floor(n / 100), r = n % 100;
    return CN_DIGITS[h] + '百' + (r === 0 ? '' : r < 10 ? '零' + CN_DIGITS[r] : (r < 20 ? '一' : '') + cn(r));
  }
  if (n < 10000) {
    const k = Math.floor(n / 1000), r = n % 1000;
    return CN_DIGITS[k] + '千' + (r === 0 ? '' : r < 100 ? '零' + cn(r) : cn(r));
  }
  return String(n);
}
function cnDur(months) {
  months = Math.max(0, Math.round(months));
  const y = Math.floor(months / 12), m = months % 12;
  if (y === 0) return m === 3 ? '一季' : m === 6 ? '半载' : cn(m) + '月';
  if (m === 0) return cn(y) + '年';
  if (m === 6) return cn(y) + '年半';
  return cn(y) + '年' + cn(m) + '月';
}

